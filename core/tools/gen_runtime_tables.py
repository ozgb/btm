"""Generate src/runtime_tables.rs (the small tables of the runtime group) from exact integer arithmetic.

    python3 -I tools/gen_runtime_tables.py [out.rs]

Same arithmetic as the kit's bitexact_tables.py; the 65536-entry sincos table is not emitted (computed on the fly).
"""
import math, struct, sys
from fractions import Fraction
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PREC = 256
ONE = 1 << PREC


def atan_scaled(x):
    for _ in range(6):
        x = x * ONE // (ONE + math.isqrt(ONE * ONE + x * x))
    x2 = x * x // ONE
    total = term = x
    n = 1
    while term:
        term = -term * x2 // ONE
        total += term // (2 * n + 1)
        n += 1
    return total * 64


def double_bits(d):
    return struct.unpack("<Q", struct.pack("<d", d))[0]


def double_double(v):
    f = Fraction(v, ONE)
    hi = float(f)
    lo = float(f - Fraction(hi))
    return double_bits(hi), double_bits(lo)


def pow10_entry(n, negative):
    v = Fraction(10) ** (-n if negative else n)
    shift = 79 - (v.numerator.bit_length() - v.denominator.bit_length())
    for s in (shift - 1, shift, shift + 1, shift + 2):
        x = v * Fraction(2) ** s
        if (x.numerator // x.denominator).bit_length() == 80:
            shift = s
            break
    x = v * Fraction(2) ** shift
    m, rem = divmod(x.numerator, x.denominator)
    if 2 * rem > x.denominator or (2 * rem == x.denominator and m & 1):
        m += 1
    exp = 0x3FFF + 79 - shift
    if m.bit_length() == 81:
        m >>= 1
        exp += 1
    assert m.bit_length() == 80
    # the kit stores low16 >= 0x8000 entries one unit of the top 64 bits high and readers take it off:
    # the net value is the plain 80-bit mantissa m
    return m, exp


def main():
    out_path = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "src/runtime_tables.rs"
    o = ["// Generated by tools/gen_runtime_tables.py; do not edit.\n\n"]
    sin = [round(math.sin(i * 2 * math.pi / 512) * 0x2000) for i in range(640)]
    o.append("pub const SIN_TABLE: [i16; 640] = [\n" + "".join(
        "    " + ", ".join(map(str, sin[i:i + 16])) + ",\n" for i in range(0, 640, 16)) + "];\n\n")
    o.append(f"pub const RAD_TO_ANGLE16: u64 = 0x{double_bits(10430.37835047):016x};\n")
    o.append(f"pub const ANGLE16_TO_RAD: u64 = 0x{double_bits(9.587379924285e-05):016x};\n\n")
    atans = []
    for k in range(17):
        v = atan_scaled(k * ONE // 16)
        if k == 16:
            pi_dd = double_double(4 * v)
            half_dd = double_double(2 * v)
        atans.append(double_double(v))
    o.append("pub const ATAN_SIXTEENTHS: [[u64; 2]; 17] = [\n" + "".join(
        f"    [0x{h:016x}, 0x{l:016x}],\n" for h, l in atans) + "];\n\n")
    ser = []
    for m in range(12):
        f = Fraction((-1) ** m, 2 * m + 1)
        hi = float(f)
        lo = float(f - Fraction(hi))
        ser.append((double_bits(hi), double_bits(lo)))
    o.append("pub const ATAN_SERIES: [[u64; 2]; 12] = [\n" + "".join(
        f"    [0x{h:016x}, 0x{l:016x}],\n" for h, l in ser) + "];\n\n")
    o.append("pub const PI_PI_HALF: [[u64; 2]; 2] = [\n" + "".join(
        f"    [0x{h:016x}, 0x{l:016x}],\n" for h, l in (pi_dd, half_dd)) + "];\n\n")
    for name, neg in (("POW10_POS", False), ("POW10_NEG", True)):
        ents = [pow10_entry((i % 7 + 1) * 8 ** (i // 7), neg) for i in range(29)]
        o.append(f"/// (80-bit mantissa, biased exponent)\npub const {name}: [(u128, u16); 29] = [\n" + "".join(
            f"    (0x{m:020x}, 0x{e:04x}),\n" for m, e in ents) + "];\n\n")
    out_path.write_text("".join(o))
    print("wrote", out_path)


main()
